"""Table 1 (CPU): main results on both backbones, from locked results only. Editor rows: month, v5's confirm5 worlds (v5 L cells,
experiments/composability_mechanisms_v4/results/chains.csv), seed medians; one-way plus R_2N unless stated. Prediction row: v5 L1
per-world agreement. Held-out templates: v6 M1 (S-RRR-16, month-mt). Binding: v7 K (bind3, Att2L-U8 over 8 seeds: median R_30, max R_100; BART only).
Writes generated/tables/table1.tex and records the inputs (SHA256) in generated/tables/manifest.json."""
import csv
from collections import defaultdict
import numpy as np
from common import *

V5C = 'experiments/composability_mechanisms_v4/results/chains.csv'; V5P = 'experiments/composability_mechanisms_v4/results/predictions.json'
V6P = 'experiments/composability_mechanisms_v5/results/predictions.json'; V7P = 'experiments/composability_mechanisms_v6/results/predictions.json'


def main():
    require_slurm(); R = defaultdict(dict)
    with open(REPO / V5C) as f:
        for r in csv.DictReader(f):
            if r['domain'] == 'month': R[r['backbone'], r['method'], r['path'].replace('_from_start', '')][int(r['t'])] = float(r['R_t'])
    def med(bb, stems, path, t):
        v = [d[t] for (b, m, p), d in R.items() if b == bb and p == path and any(m == s or m.startswith(s + '_s') for s in stems) and t in d]
        return float(np.median(v)) if v else None
    p5 = read(V5P)['L']['per_backbone']; p6 = read(V6P); p7 = read(V7P)
    rows = [
        ('Closed-form RRR-16, one-step $R_1$', lambda bb: med(bb, ['F_empty'], 'plus', 1)),
        ('Closed-form RRR-16, one-way $\\Rk{2N}$', lambda bb: med(bb, ['F_empty'], 'plus', 24)),
        ('CE editor C1, one-step $R_1$', lambda bb: med(bb, ['C1v1' if bb == 'bart' else 'C1v3'], 'plus', 1)),
        ('CE editor C1, one-way $\\Rk{2N}$', lambda bb: med(bb, ['C1v1' if bb == 'bart' else 'C1v3'], 'plus', 24)),
        ('Unrolled CE C1-U4, one-way $\\Rk{2N}$', lambda bb: med(bb, ['C1U4v4' if bb == 'bart' else 'C1U4n'], 'plus', 24)),
        ('Unrolled CE + $L_2$ C3-U4, one-way $\\Rk{2N}$', lambda bb: med(bb, ['C3U4v4' if bb == 'bart' else 'C3U4n'], 'plus', 24)),
        ('Fundamental frozen $F\\{1\\}$, one-way $\\Rk{2N}$', lambda bb: med(bb, ['F_{1}'], 'plus', 24)),
        ('Fundamental frozen $F\\{1\\}$, alternating $\\Rk{2N}$', lambda bb: med(bb, ['F_{1}'], 'alt', 24)),
        ('Latent prediction, per-world agreement', lambda bb: p5[bb]['L1']['latent']),
        ('Naive step-1 prediction, agreement', lambda bb: p5[bb]['L1']['naive']),
        ('Unseen templates, slot-only S-RRR-16, one-way $\\Rk{2N}$', lambda bb: p6['M']['M1'].get(f'{bb}/month-mt')),
        ('Binding (bind3), two-layer editor, median $\\Rk{30}$ (8 seeds)', lambda bb: float(np.median(list(p7['K']['table']['bind3/Att2LU8/R30'].values()))) if bb == 'bart' else None),
        ('Binding (bind3), two-layer editor, max $\\Rk{100}$ (8 seeds)', lambda bb: max(p7['K']['table']['bind3/Att2LU8/R100'].values()) if bb == 'bart' else None),
    ]
    L = ['% generated by paper/scripts/table1.py from locked results; do not edit', '\\begin{tabular}{lrr}', '\\toprule & BART-base & T5Gemma \\\\ \\midrule']
    for name, fn in rows:
        L.append(name + ' & ' + ' & '.join('--' if (v := fn(bb)) is None else f'{v:.2f}' for bb in ('bart', 't5')) + ' \\\\')
    L += ['\\bottomrule', '\\end{tabular}']
    (PAPER / 'generated/tables/table1.tex').write_text('\n'.join(L) + '\n')
    m = PAPER / 'generated/tables/manifest.json'; man = json.loads(m.read_text()) if m.exists() else {}
    man['table1'] = dict(script='paper/scripts/table1.py', inputs={f: sha(f) for f in (V5C, V5P, V6P, V7P)}); m.write_text(json.dumps(man, indent=1))
    print('\n'.join(L), flush=True)


if __name__ == '__main__':
    main()
