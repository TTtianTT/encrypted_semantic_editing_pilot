"""Timeline table (CPU; PLAN v9 P9e, review M7): per round the first commit, the lock commit and date, the report commit and the amendment
or erratum files, from experiments/composability_mechanisms_v8/results/p9e.json (built from git history). Writes
generated/tables/timeline.tex and records the input in generated/tables/manifest.json."""
from common import *

P = 'experiments/composability_mechanisms_v8/results/p9e.json'


def main():
    require_slurm(); t = read(P)['timeline']; L = ['% generated by paper/scripts/timeline_table.py; do not edit', '\\begin{tabular}{llllll}',
                                                '\\toprule round & directory & first commit & lock (date) & report & amendments / errata \\\\ \\midrule']
    esc = lambda s: str(s).replace('_', '\\_')
    for r in t + [dict(round='v9', dir='composability_mechanisms_v8', first_commit=read('experiments/composability_mechanisms_v8/protocol_lock.json')['lock_commit'][:7] + ' (lock)',
                       lock_commit=read('experiments/composability_mechanisms_v8/protocol_lock.json')['lock_commit'][:7], lock_date='2026-11-28', report_commit='see REPORT.md',
                       amendments_errata='AMENDMENT_01.md AMENDMENT_02.md')]:
        L.append(f"{r['round']} & \\texttt{{{esc(r['dir'])}}} & {esc(r['first_commit'])} & {esc(r['lock_commit'])} ({esc(r['lock_date'])}) & {esc(r['report_commit'])} & {esc(r['amendments_errata']).strip() or '--'} \\\\")
    L += ['\\bottomrule', '\\end{tabular}']; (PAPER / 'generated/tables/timeline.tex').write_text('\n'.join(L) + '\n')
    m = PAPER / 'generated/tables/manifest.json'; man = json.loads(m.read_text()) if m.exists() else {}; man['timeline'] = dict(script='paper/scripts/timeline_table.py', inputs={P: sha(P)}); m.write_text(json.dumps(man, indent=1))


if __name__ == '__main__':
    main()
