"""Scale table (CPU): T5Gemma B-B, L-L (ladder, exploratory, closed form) and 9B-9B (unit G, locked) on weekday and month template 0, v8
confirm7; from experiments/composability_mechanisms_v7/results/predictions.json and g_prep_<bb>.json. Columns: reconstruction (train and dev),
r*_pred (Proposition 1), observed r* (smallest RRR-r of the grid, including 16, with one-way R_2N >= 0.95; '>16' if none), F{1} one-way /
alternating and F_not1 one-way R_2N on RRR-16, whether s_1 is the smallest plane, per-world agreement of the slot readout pooled over the
size's cells. Writes generated/tables/scale.tex and records the inputs in generated/tables/manifest.json."""
from common import *

P8 = 'experiments/composability_mechanisms_v7/results/predictions.json'
GP = lambda bb: f'experiments/composability_mechanisms_v7/results/g_prep_{bb}.json'
SIZES = [('t5_bb', 'B-B'), ('t5_ll', 'L-L'), ('t5_9b', '9B-9B')]


def main():
    require_slurm(); p = read(P8); L = ['% generated by paper/scripts/scale_table.py from locked results; do not edit', '\\begin{tabular}{llrrrrrrcr}',
                                       '\\toprule size & domain & recon. & $r^\\star_{\\mathrm{pred}}$ & $r^\\star$ & $F\\{1\\}$ one-way & $F\\{1\\}$ alt. & $F_{\\neg 1}$ one-way & $s_1$ min & agree \\\\ \\midrule']
    for bb, name in SIZES:
        r = p['G'] if bb == 't5_9b' else p['ladder'][bb]; gp = read(GP(bb))
        for d in ('weekday', 'month'):
            rec = gp['domains'][d]['reconstruction']['rate']; x = r['domains'][d]
            if 'skipped' in x: L.append(f'{name} & {d} & {rec:.3f} & \\multicolumn{{7}}{{l}}{{skipped (reconstruction gate)}} \\\\'); continue
            cells = r['cells']; grid = sorted({int(k.split('/')[1][3:]) for k in cells if k.startswith(f'{d}/RRR') and k.endswith('/plus')} | {16})
            ob = lambda q: cells[f'{d}/{"F_empty" if q == 16 else f"RRR{q}"}/plus']['obs_rate']
            rs = next((q for q in grid if ob(q) >= .95), None); g3 = x['G3']['observed']
            L.append(f"{name} & {d} & {rec:.3f} & {x['G2']['rstar_pred']} & {rs if rs is not None else '$>16$'} & {g3['F1_plus']:.2f} & {g3['F1_alt']:.2f} & {g3['Fnot1_plus']:.2f} & "
                     f"{'yes' if x['G4']['holds'] else 'no'} & {r['prediction']['latent']:.2f} \\\\")
    L += ['\\bottomrule', '\\end{tabular}']; (PAPER / 'generated/tables/scale.tex').write_text('\n'.join(L) + '\n')
    m = PAPER / 'generated/tables/manifest.json'; man = json.loads(m.read_text()) if m.exists() else {}
    man['scale'] = dict(script='paper/scripts/scale_table.py', inputs={f: sha(f) for f in [P8] + [GP(bb) for bb, _ in SIZES]}); m.write_text(json.dumps(man, indent=1))
    print('\n'.join(L), flush=True)


if __name__ == '__main__':
    main()
