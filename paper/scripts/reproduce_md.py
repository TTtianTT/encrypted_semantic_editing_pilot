"""W7 (CPU): write paper/REPRODUCE.md from the generated manifests, so the listed commands and input hashes are always the ones the
current build used: figs/manifest.json (figures), claims.yaml (numbers.tex evidence and lock commits) and the predictions files read by
predictions_table.py (tables). Hashes are recomputed here and compared with the manifests; a mismatch is reported in the file and makes
the script exit 1."""
import sys
import yaml
from common import *
import predictions_table as pt

SB = 'SCRIPT={s} sbatch --parsable --export=ALL paper/job_cpu.slurm'


def main():
    require_slurm(); bad = []; L = []
    claims = yaml.safe_load((PAPER / 'claims.yaml').read_text()); figs = json.loads((PAPER / 'figs/manifest.json').read_text())
    def h(f, want=None):
        got = sha(f) if (REPO / f).exists() else 'MISSING'
        if want is not None and got != want: bad.append(f); return f'`{got}` (manifest: `{want}`, MISMATCH)'
        return f'`{got}`'
    L += ['# REPRODUCE (generated by `paper/scripts/reproduce_md.py`; do not edit)', '',
          'All computation runs through Slurm (`sbatch` + `srun`); the login node only runs git and file edits. Every script below is CPU-only',
          'and reads locked experiment results; none writes into `experiments/`. Run from the repository root of branch `paper/composability`.', '',
          '## Order', '', '```bash']
    for s in ('scripts/build_claims.py', 'scripts/predictions_table.py', *[f'figs/make_{k}.py' for k in sorted(figs)], 'scripts/reproduce_md.py', 'check.py'):
        L.append(SB.format(s=s))
    L += ['```', '', 'Then compile `paper/main.tex` (pdflatex, bibtex, pdflatex x2).', '', '## Lock commits of the experiment rounds', '',
          '| round | lock commit |', '| --- | --- |']
    L += [f'| {r} | `{c}` |' if c else f'| {r} | not locked yet |' for r, c in claims['lock_commits'].items()]
    L += ['', '## Figures', '', '| figure | command | input | SHA256 |', '| --- | --- | --- | --- |']
    for k in sorted(figs):
        for i, (f, s) in enumerate(sorted(figs[k]['inputs'].items())):
            L.append(f"| {k if i == 0 else ''} | {'`' + SB.format(s=f'figs/make_{k}.py') + '`' if i == 0 else ''} | `{f}` | {h(f, s)} |")
    L += ['', '## Tables', '', f"`generated/tables/predictions_all.tex` and `generated/tables/table2.tex`: `{SB.format(s='scripts/predictions_table.py')}`", '',
          '| round | input | SHA256 |', '| --- | --- | --- |']
    for r, d, f in pt.ROUNDS:
        p = f'experiments/{d}/{f}'
        if (REPO / p).exists(): L.append(f'| {r} | `{p}` | {h(p)} |')
    L += ['', '## Numbers (`generated/numbers.tex`)', '', f"Command: `{SB.format(s='scripts/build_claims.py')}`. Evidence files per claim (hash at build time):", '',
          '| claim | file | SHA256 |', '| --- | --- | --- |']
    for c in claims['claims']:
        for i, (f, s) in enumerate(sorted(c['evidence'].items())):
            L.append(f"| {c['id'] if i == 0 else ''} | `{f}` | {h(f, s)} |")
    pend = [n['macro'] for c in claims['claims'] for n in c['numbers'] if n['pending']]
    L += ['', f"Pending macros (rendered as `\\TODO{{v6}}` until v6 is merged): {', '.join(pend) if pend else 'none'}.", '']
    if bad: L += ['## MISMATCHES', '', *[f'- `{f}`' for f in bad], '']
    (PAPER / 'REPRODUCE.md').write_text('\n'.join(L)); print('REPRODUCE.md written; mismatches', len(bad), flush=True); sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
